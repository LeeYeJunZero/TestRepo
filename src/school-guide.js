const COEDU = { 남여공학: '남녀공학', 남: '남학교', 여: '여학교' };

// schools.json 한 줄 → 페이지에 쓰는 정보
export function describeSchool(x) {
  const s = { name: x[0], kind: x[1], region: x[2], city: x[3], code: x[4], fond: x[5], coedu: x[6], hsKind: x[7], gen: x[8], track: x[9], founded: x[10], office: x[11], addr: x[12], home: x[13], shift: x[14], majors: x[15] || [] };
  const level = levelOf(s.kind);
  const year = /^\d{8}$/.test(s.founded) && +s.founded.slice(0, 4) >= 1880 ? +s.founded.slice(0, 4) : 0;
  const type = typeLabel(s);
  const planned = /(개교|신설)\s*예정/.test(s.name);
  const place = [s.region, s.city === '기타' ? '' : s.city].filter(Boolean).join(' ');
  const coedu = COEDU[s.coedu] || '';
  const intro = planned
    ? `${s.name}${josa(s.name, '은', '는')} NEIS에 개교 예정으로 등록된 ${place} 소재 학교입니다.`
    : `${s.name}${josa(s.name, '은', '는')} ${place}에 있는 ${[s.fond && s.fond !== '기타' ? s.fond : '', coedu, type].filter(Boolean).join(' ')}입니다.${year ? ` ${year}년에 설립되었습니다.` : ''}`;
  const facts = [
    ['학교 유형', type], ['설립 구분', s.fond], ['남녀 구분', coedu], ['설립 연도', year && !planned ? `${year}년` : ''],
    ['운영', s.shift && s.shift !== '주간' ? s.shift : ''], ['관할 교육청', s.office], ['소재지', s.addr]
  ].filter(([, v]) => v);
  return { ...s, level, type, intro, note: typeNote(s, level), facts, year };
}
