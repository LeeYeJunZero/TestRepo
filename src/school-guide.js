const GENERIC = (subject) => `학생이 따르는 교육과정과 현재 수준을 먼저 확인한 뒤, ${subject} 학습 목표와 진도를 1:1로 맞춥니다.`;

export const ALL_SUBJECTS = ['국어', '영어', '수학', '사회', '과학', '한국사', '물리', '화학', '생물', '코딩', '영어회화'];

export function studyGuide(level) {
  const g = GUIDES[level];
  if (!g) return ALL_SUBJECTS.map((subject) => ({ subject, text: GENERIC(subject) }));
  return ALL_SUBJECTS.filter((s) => g[s]).map((subject) => ({ subject, text: g[subject] }));
}

// 받침에 맞는 조사 (한글로 끝나지 않으면 병기)
const josa = (word, withBatchim, without) => {
  const c = word.charCodeAt(word.length - 1);
  if (c < 0xac00 || c > 0xd7a3) return `${withBatchim}(${without})`;
  return (c - 0xac00) % 28 ? withBatchim : without;
};

function typeLabel(s) {
  if (s.track === '산업수요 맞춤형 고등학교') return '마이스터고등학교';
  if (s.track) return `${s.track.replace('계열', '')} 계열 특수목적고등학교`;
  if (s.hsKind === '특성화고') return '특성화고등학교';
  if (s.hsKind === '자율고') return '자율고등학교';
  if (s.hsKind === '일반고') return '일반고등학교';
  return s.kind;
}

