export const levelOf = (kind) => {
  if (/초등|\(초\)/.test(kind)) return 'elementary';
  if (/중학교|\(중\)|고등공민/.test(kind)) return 'middle';
  if (/고등|\(고\)/.test(kind)) return 'high';
  return 'other';
};

